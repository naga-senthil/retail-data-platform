
CREATE TABLE IF NOT EXISTS RETAIL_DW.MONITORING.LOAD_HISTORY (
    LOAD_ID           VARCHAR,
    PIPELINE_NAME     VARCHAR,
    STARTED_AT        TIMESTAMP_NTZ,
    COMPLETED_AT      TIMESTAMP_NTZ,
    STATUS            VARCHAR,
    ROWS_INSERTED     NUMBER DEFAULT 0,
    ROWS_UPDATED      NUMBER DEFAULT 0,
    ERROR_MESSAGE     VARCHAR
);

CREATE TABLE IF NOT EXISTS RETAIL_DW.MONITORING.FILE_LOAD_HISTORY (
    FILE_NAME         VARCHAR,
    LOAD_ID           VARCHAR,
    FILE_STATUS       VARCHAR,
    ROWS_LOADED       NUMBER DEFAULT 0,
    FIRST_SEEN_AT     TIMESTAMP_NTZ,
    LOADED_AT         TIMESTAMP_NTZ,
    ERROR_MESSAGE     VARCHAR
);
