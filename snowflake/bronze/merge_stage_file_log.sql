
MERGE INTO RETAIL_DW.BRONZE.STAGE_FILE_LOG AS TARGET
USING (
    SELECT
        '<% FILE_PATH %>' AS FILE_PATH,
        '<% FILE_NAME %>' AS FILE_NAME,
        '<% BATCH_ID %>' AS BATCH_ID,
        '<% FILE_CATEGORY %>' AS FILE_CATEGORY
) AS SOURCE
ON TARGET.FILE_PATH = SOURCE.FILE_PATH

WHEN MATCHED THEN UPDATE SET
    FILE_NAME = SOURCE.FILE_NAME,
    BATCH_ID = SOURCE.BATCH_ID,
    FILE_CATEGORY = SOURCE.FILE_CATEGORY,
    UPLOAD_STATUS = 'UPLOADED',
    UPLOADED_AT = COALESCE(
        TARGET.UPLOADED_AT,
        CURRENT_TIMESTAMP()
    ),
    LAST_CHECKED_AT = CURRENT_TIMESTAMP(),
    ERROR_MESSAGE = NULL

WHEN NOT MATCHED THEN INSERT (
    FILE_PATH,
    FILE_NAME,
    BATCH_ID,
    FILE_CATEGORY,
    UPLOAD_STATUS,
    UPLOADED_AT,
    LAST_CHECKED_AT
)
VALUES (
    SOURCE.FILE_PATH,
    SOURCE.FILE_NAME,
    SOURCE.BATCH_ID,
    SOURCE.FILE_CATEGORY,
    'UPLOADED',
    CURRENT_TIMESTAMP(),
    CURRENT_TIMESTAMP()
);
