USE DATABASE RETAIL_DW;
USE SCHEMA BRONZE;

-- 1. Tracks files discovered and uploaded to the internal stage.
CREATE TABLE IF NOT EXISTS RETAIL_DW.BRONZE.STAGE_FILE_LOG (
    FILE_PATH        VARCHAR NOT NULL,
    FILE_NAME        VARCHAR NOT NULL,
    BATCH_ID         VARCHAR,
    FILE_CATEGORY    VARCHAR,
    FILE_SIZE_BYTES  NUMBER,
    UPLOAD_STATUS    VARCHAR DEFAULT 'DISCOVERED',
    DISCOVERED_AT    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPLOADED_AT      TIMESTAMP_NTZ,
    LAST_CHECKED_AT  TIMESTAMP_NTZ,
    ERROR_MESSAGE    VARCHAR
);

-- 2. Tracks ingestion execution and COPY INTO results.
CREATE TABLE IF NOT EXISTS RETAIL_DW.BRONZE.LOAD_AUDIT (
    LOAD_ID          NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    BATCH_ID         VARCHAR,
    FILE_PATH        VARCHAR,
    TARGET_TABLE     VARCHAR,
    LOAD_STATUS      VARCHAR,
    ROWS_PARSED      NUMBER DEFAULT 0,
    ROWS_LOADED      NUMBER DEFAULT 0,
    ROWS_SKIPPED     NUMBER DEFAULT 0,
    ERROR_COUNT      NUMBER DEFAULT 0,
    STARTED_AT       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    COMPLETED_AT     TIMESTAMP_NTZ,
    ERROR_MESSAGE    VARCHAR,
    RUN_TOKEN        VARCHAR
);

