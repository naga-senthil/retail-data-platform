WITH batch_file_status AS (
    SELECT
        REGEXP_SUBSTR(FILE_PATH, 'batch_[0-9]{8}') AS BATCH_NAME,
        COUNT(DISTINCT TARGET_TABLE) AS FILE_COUNT
    FROM RETAIL_DW.BRONZE.LOAD_AUDIT
    WHERE LOAD_STATUS IN (
        'SUCCESS',
        'PARTIAL_SUCCESS',
        'SKIPPED'
    )
    GROUP BY 1
)
SELECT COALESCE(
    MAX(REPLACE(BATCH_NAME, 'batch_', '')),
    '00000000'
) AS LATEST_COMPLETE_BATCH
FROM batch_file_status
WHERE FILE_COUNT = 4;