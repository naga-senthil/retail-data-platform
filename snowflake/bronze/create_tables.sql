USE DATABASE RETAIL_DW;
USE SCHEMA BRONZE;

-- 1. Customers
CREATE TABLE IF NOT EXISTS CUSTOMERS (
    CUSTOMER_ID VARCHAR,
    CUSTOMER_UNIQUE_ID VARCHAR,
    CUSTOMER_ZIP_CODE_PREFIX VARCHAR,
    CUSTOMER_CITY VARCHAR,
    CUSTOMER_STATE VARCHAR,
    LOAD_BATCH_ID VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

-- 2. Geolocation
CREATE TABLE IF NOT EXISTS GEOLOCATION (
    GEOLOCATION_ZIP_CODE_PREFIX VARCHAR,
    GEOLOCATION_LAT VARCHAR,
    GEOLOCATION_LNG VARCHAR,
    GEOLOCATION_CITY VARCHAR,
    GEOLOCATION_STATE VARCHAR,
    LOAD_BATCH_ID VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

-- 3. Order items
CREATE TABLE IF NOT EXISTS ORDER_ITEMS (
    ORDER_ID VARCHAR,
    ORDER_ITEM_ID VARCHAR,
    PRODUCT_ID VARCHAR,
    SELLER_ID VARCHAR,
    SHIPPING_LIMIT_DATE VARCHAR,
    PRICE VARCHAR,
    FREIGHT_VALUE VARCHAR,
    LOAD_BATCH_ID VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

-- 4. Order payments
CREATE TABLE IF NOT EXISTS ORDER_PAYMENTS (
    ORDER_ID VARCHAR,
    PAYMENT_SEQUENTIAL VARCHAR,
    PAYMENT_TYPE VARCHAR,
    PAYMENT_INSTALLMENTS VARCHAR,
    PAYMENT_VALUE VARCHAR,
    LOAD_BATCH_ID VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

-- 5. Order reviews
CREATE TABLE IF NOT EXISTS ORDER_REVIEWS (
    REVIEW_ID VARCHAR,
    ORDER_ID VARCHAR,
    REVIEW_SCORE VARCHAR,
    REVIEW_COMMENT_TITLE VARCHAR,
    REVIEW_COMMENT_MESSAGE VARCHAR,
    REVIEW_CREATION_DATE VARCHAR,
    REVIEW_ANSWER_TIMESTAMP VARCHAR,
    LOAD_BATCH_ID VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

-- 6. Orders
CREATE TABLE IF NOT EXISTS ORDERS (
    ORDER_ID VARCHAR,
    CUSTOMER_ID VARCHAR,
    ORDER_STATUS VARCHAR,
    ORDER_PURCHASE_TIMESTAMP VARCHAR,
    ORDER_APPROVED_AT VARCHAR,
    ORDER_DELIVERED_CARRIER_DATE VARCHAR,
    ORDER_DELIVERED_CUSTOMER_DATE VARCHAR,
    ORDER_ESTIMATED_DELIVERY_DATE VARCHAR,
    LOAD_BATCH_ID VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

-- 7. Products
-- Preserve source spelling "lenght" to match CSV headers.
CREATE TABLE IF NOT EXISTS PRODUCTS (
    PRODUCT_ID VARCHAR,
    PRODUCT_CATEGORY_NAME VARCHAR,
    PRODUCT_NAME_LENGHT VARCHAR,
    PRODUCT_DESCRIPTION_LENGHT VARCHAR,
    PRODUCT_PHOTOS_QTY VARCHAR,
    PRODUCT_WEIGHT_G VARCHAR,
    PRODUCT_LENGTH_CM VARCHAR,
    PRODUCT_HEIGHT_CM VARCHAR,
    PRODUCT_WIDTH_CM VARCHAR,
    LOAD_BATCH_ID VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

-- 8. Sellers
CREATE TABLE IF NOT EXISTS SELLERS (
    SELLER_ID VARCHAR,
    SELLER_ZIP_CODE_PREFIX VARCHAR,
    SELLER_CITY VARCHAR,
    SELLER_STATE VARCHAR,
    LOAD_BATCH_ID VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

-- 9. Product category translation
CREATE TABLE IF NOT EXISTS CATEGORY_TRANSLATION (
    PRODUCT_CATEGORY_NAME VARCHAR,
    PRODUCT_CATEGORY_NAME_ENGLISH VARCHAR,
    LOAD_BATCH_ID VARCHAR,
    INGESTED_AT TIMESTAMP_NTZ
);

-- 10. Tracks files discovered and uploaded to the internal stage.
CREATE TABLE IF NOT EXISTS RETAIL_DW.BRONZE.STAGE_FILE_LOG (
    FILE_PATH        VARCHAR NOT NULL,
    FILE_NAME        VARCHAR NOT NULL,
    BATCH_ID         VARCHAR,
    FILE_CATEGORY    VARCHAR,
    FILE_SIZE_BYTES  NUMBER,
    UPLOAD_STATUS    VARCHAR DEFAULT 'DISCOVERED',
    DISCOVERED_AT    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPLOADED_AT      TIMESTAMP_NTZ,
    LAST_CHECKED_AT  TIMESTAMP_NTZ,
    ERROR_MESSAGE    VARCHAR
);

-- 11. Tracks ingestion execution and COPY INTO results.
CREATE TABLE IF NOT EXISTS RETAIL_DW.BRONZE.LOAD_AUDIT (
    LOAD_ID          NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    BATCH_ID         VARCHAR,
    FILE_PATH        VARCHAR,
    TARGET_TABLE     VARCHAR,
    LOAD_STATUS      VARCHAR,
    ROWS_PARSED      NUMBER DEFAULT 0,
    ROWS_LOADED      NUMBER DEFAULT 0,
    ROWS_SKIPPED     NUMBER DEFAULT 0,
    ERROR_COUNT      NUMBER DEFAULT 0,
    STARTED_AT       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    COMPLETED_AT     TIMESTAMP_NTZ,
    ERROR_MESSAGE    VARCHAR,
    RUN_TOKEN        VARCHAR
);

