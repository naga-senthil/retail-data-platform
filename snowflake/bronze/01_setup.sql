
-- Configure Bronze layer
USE DATABASE RETAIL_DW;
USE WAREHOUSE RETAIL_WH;

-- CSV file format
CREATE FILE FORMAT IF NOT EXISTS BRONZE.CSV_FORMAT
    TYPE = CSV
    COMPRESSION = AUTO
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    NULL_IF = ('NULL', 'null')
    TRIM_SPACE = TRUE
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

-- Internal stage for batch ingestion
CREATE STAGE IF NOT EXISTS BRONZE.RETAIL_STAGE
    FILE_FORMAT = BRONZE.CSV_FORMAT
    COMMENT = 'Internal stage for retail batch ingestion';
